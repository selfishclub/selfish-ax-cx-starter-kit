/**
 * 슬랙 카드에 싣기 전에 개인정보를 가린다 (2026-09-28)
 *
 * 원칙 — 회원 화면에 전화번호를 내려보내지 않는 것과 같다.
 * 카드에는 「무슨 문의인지」만 보이면 된다. 누구인지·번호·금액은 필요 없다.
 * 원본은 카카오 관리자 화면에 그대로 있으니, 답할 때는 「원본 열기」로 간다.
 */

/** 이름 가리기 — 가운데를 * 로. 「김하늘」→「김*늘」, 「하늘」→「하*」, 영문·닉네임은 앞 글자만 */
function maskName(name) {
  const s = String(name || '').trim();
  if (!s) return '(이름 없음)';
  const chars = [...s];
  if (chars.length === 1) return chars[0] + '*';
  if (chars.length === 2) return chars[0] + '*';
  if (chars.length <= 4) return chars[0] + '*'.repeat(chars.length - 2) + chars[chars.length - 1];
  return chars[0] + '*'.repeat(3);
}

/** 본문 가리기 — 전화번호 · 이메일 · 카드/계좌/금액 같은 긴 숫자 */
function maskText(text) {
  if (!text) return '';
  return (
    String(text)
      // 이메일
      .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '[이메일]')
      // 휴대폰·전화 (010-1234-5678 · 01012345678 · 02-123-4567 · +82 10 …)
      .replace(/(?<!\d)(\+82[\s-]?)?0?1[016789][\s-]?\d{3,4}[\s-]?\d{4}(?!\d)/g, '[전화번호]')
      .replace(/(?<!\d)0\d{1,2}[\s-]?\d{3,4}[\s-]?\d{4}(?!\d)/g, '[전화번호]')
      // 카드번호처럼 4자리 묶음이 이어지는 것
      .replace(/\d{4}[\s-]\d{4}[\s-]\d{4}[\s-]\d{2,4}/g, '[긴 숫자]')
      // 그 외 7자리 이상 연속 숫자(계좌·주문번호·금액) — 날짜(8자리)도 같이 가려지지만 카드엔 필요 없다
      .replace(/\d{7,}/g, '[긴 숫자]')
      // 금액 표기 (12,000원 · 120000원)
      .replace(/\d{1,3}(,\d{3})+\s?원/g, '[금액]')
      // 본인 이름을 번호·이메일·뒷자리와 같이 적는 경우 — 「홍길동 [전화번호]」 「홍길동/1234」 「홍길동 / [이메일]」
      .replace(/([가-힣]{2,4})(\s*[\/,·]?\s*)(\[전화번호\]|\[이메일\]|\d{4}(?!\d))/g, '[이름]$2$3')
      .replace(/(\[전화번호\]|\[이메일\])(\s*[\/,·]?\s*)([가-힣]{2,4})(?=\s*(입니다|이에요|예요|이요|이고|이구요))/g, '$1$2[이름]')
      // 「신청자명 : 홍길동」 「입금자: 홍길동(회사)」 「예금주 : 홍길동」 「신청자명: 홍길동」
      .replace(/(신청자명?|입금자명?|예금주|성함|이름|수신자|참가자)\s*[:：]\s*([가-힣]{2,4})(\([^)]*\))?/g, '$1: [이름]')
      // 「길동님」 「홍길동님」 — 답변에서 이름을 부르는 형태. 「회원님」 「고객님」 「담당자님」 「선생님」 「대표님」은 이름이 아니다
      .replace(/(?<![가-힣])([가-힣]{2,3})님(?![가-힣])/g, (m, n) => /^(회원|고객|담당자|선생|대표|관리자|매니저|여러분|사장|팀장|대리|과장|부장|이사|작가|강사|멤버|크루|운영자|주최자|참가자|신청자|사용자|본인|어머|아버|부모|형|누나|언니|오빠)$/.test(n) ? m : '[이름]님')
      // 「홍길동 대표」 「홍길동대표입니다」
      .replace(/([가-힣]{2,4})\s?(대표|이사|팀장|매니저|작가|강사)(?=입니다|님|이|가|\s|$)/g, '[이름] $2')
  );
}

module.exports = { maskName, maskText };
